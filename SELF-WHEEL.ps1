# SELF-WHEEL.ps1 - The Wheel that Builds Wheels!
# This script makes GAIH self-generating!

Write-Host "SELF-WHEEL ACTIVATED - Building new wheel..." -ForegroundColor Yellow

param([string]$NewWheelName)

if(-not $NewWheelName){ $NewWheelName = Read-Host "What new wheel to build? (e.g. GAIH-HEALTH, GAIH-FACTORY, GAIH-BANK)" }

$port = (Get-Random -Minimum 13000 -Maximum 20000)
$path = "C:\1989SHACK-GAIH\$NewWheelName"
New-Item -ItemType Directory -Force -Path $path | Out-Null

# AI Generates the wheel code itself!
$code = @"
const express=require('express');const app=express();app.use(express.json());
// SELF-GENERATED WHEEL: $NewWheelName
// Generated by SELF-WHEEL at $(Get-Date)
// Location: Monrovia Data Center

let data={wheel:'$NewWheelName',status:'SELF-GENERATED',created:'$(Get-Date)',location:'Monrovia',self_rebuild:true,port:$port};

app.get('/',(req,res)=>res.json(data));
app.get('/api/$($NewWheelName.ToLower())/status',(req,res)=>res.json({wheel:'$NewWheelName',online:true,self_healing:'PM2 restart:always',deployed_by:'SELF-WHEEL',message:'I was self-generated by GAIH! No human coded me!'}));
app.post('/api/$($NewWheelName.ToLower())/action',(req,res)=>{console.log('Action for $NewWheelName',req.body);res.json({action:'done',wheel:'$NewWheelName',by:'self-wheel'});});

app.listen($port,()=>console.log('$NewWheelName SELF-GENERATED on $port'));
"@

$code | Out-File "$path\server.js" -Encoding utf8
Set-Location $path
npm init -y | Out-Null
npm install express | Out-Null

# Self-Deploy!
pm2 start "$path\server.js" --name $NewWheelName
pm2 save

# Add firewall
New-NetFirewallRule -DisplayName $NewWheelName -Direction Inbound -Action Allow -Protocol TCP -LocalPort $port -ErrorAction SilentlyContinue | Out-Null

Write-Host "$NewWheelName SELF-GENERATED & SELF-DEPLOYED on port $port!" -ForegroundColor Green
Write-Host "Test: http://localhost:$port/" -ForegroundColor Cyan
Write-Host "PM2: pm2 list should show $NewWheelName ONLINE!" -ForegroundColor Yellow